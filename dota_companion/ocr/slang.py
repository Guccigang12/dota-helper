# Compiled regex patterns for fast slang replacement
_SLANG_WORD_PATTERNS = [
    (re.compile(r"\b" + re.escape(k) + r"\b", re.IGNORECASE), v)
    for k, v in DOTA_SLANG_DICT.items()
    if re.match(r"^[a-zA-Z0-9_\s]+$", k)
]

_SLANG_NON_ASCII_PATTERNS = [
    (k, v) for k, v in DOTA_SLANG_DICT.items()
    if not re.match(r"^[a-zA-Z0-9_\s]+$", k)
]


def enhance_text_with_slang(text: str) -> str:
    """
    Substitutes or annotations common Dota 2 slang terms in raw OCR text
    before passing to general translators (e.g. Google Translate).
    """
    if not text:
        return ""

    result = text
    # Replace non-ascii words (e.g. Chinese characters)
    for k, v in _SLANG_NON_ASCII_PATTERNS:
        if k in result:
            result = result.replace(k, f" {v} ")

    # Replace ascii/latin word boundaries
    for pattern, v in _SLANG_WORD_PATTERNS:
        result = pattern.sub(v, result)

    # Clean redundant whitespace
    return re.sub(r"\s+", " ", result).strip()


